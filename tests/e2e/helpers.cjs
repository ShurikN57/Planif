const http = require('node:http'),
  fs = require('node:fs'),
  path = require('node:path');
const {chromium} = require('playwright');
const root = path.join(__dirname, '../..');
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.png': 'image/png'
};

// Serves the repository under /Planif/, like GitHub Pages.
function startServer() {
  const server = http.createServer((req, res) => {
    const url = new URL(req.url, 'http://localhost');
    let file = decodeURIComponent(url.pathname.replace(/^\/Planif\//, '/'));
    if (file.endsWith('/')) file += 'index.html';
    const full = path.join(root, path.normalize(file));
    if (!full.startsWith(root + path.sep) || !fs.existsSync(full) || fs.statSync(full).isDirectory()) {
      res.writeHead(404).end('Not found');
      return;
    }
    res.writeHead(200, {
      'Content-Type': TYPES[path.extname(full)] || 'application/octet-stream',
      'Cache-Control': 'no-store'
    });
    fs.createReadStream(full).pipe(res);
  });
  return new Promise(resolve =>
    server.listen(0, '127.0.0.1', () =>
      resolve({server, url: `http://127.0.0.1:${server.address().port}/Planif/`})
    )
  );
}

