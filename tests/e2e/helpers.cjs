// Stores a saved plan generated by the real engine, as the app would; returns its calendar day keys.
async function seedPlan(page, {id = 'plan-test', state = STATE} = {}) {
  return page.evaluate(
    ({id, st}) => {
      const E = PlanifEngine.createEngine();
      const C = E.buildCalendar(st, E.predict(st));
      E.ensurePlanifSessionIds(C);
      localStorage.setItem(
        'planif-global-v1',
        JSON.stringify({
          vma: '17',
          s2: '14',
          s1lo: '11.5',
          s1hi: '12',
          refDist: '0',
          refTime: '19:25',
          profile: '1'
        })
      );
      localStorage.setItem('planif-mode-v1', 'cal');
      localStorage.setItem('planif-weekly-balance-v2', 'saved');
      localStorage.setItem(
        'planif-active-plan-v1',
        E.serializeSavedPlans({
          id,
          title: `10 km · ${st.calRace}`,
          createdAt: '2026-11-08T10:00:00.000Z',
          updatedAt: '2026-11-08T10:00:00.000Z',
          structure: {calDist: '1', calRace: st.calRace, calStart: st.calStart},
          plan: JSON.parse(JSON.stringify(C))
        })
      );
      return C.weeks.flatMap(w => w.days.map(d => E.planDateKey(d.date)));
    },
    {id, st: state}
  );
}

// Read the dates from the rendered calendar, without calling the conversion helper under test.
async function calendarDays(page) {
  await page.click('[data-tab="cal"]');
  const weeks = page.locator('#scr-cal button.cwHead[data-week]');
  await weeks.first().waitFor();
  const days = [];
  for (const week of await weeks.all()) {
    const index = await week.getAttribute('data-week');
    if ((await week.getAttribute('aria-expanded')) !== 'true') await week.click();
    const rows = page.locator(`#scr-cal .dayRow[data-move-week="${index}"][data-move-date]`);
    await rows.first().waitFor();
    days.push(...(await rows.evaluateAll(elements => elements.map(el => el.dataset.moveDate))));
  }
  return days;
}

async function openApp(browser, url, {timezoneId = 'Europe/Paris', ...options} = {}) {
  const context = await browser.newContext({timezoneId, viewport: {width: 390, height: 844}, ...options});
  context.setDefaultTimeout(15000);
  const page = await context.newPage(),
    errors = [];
  page.on('pageerror', error => errors.push(error.message));
  // CSP violations (for instance an inline style) are reported as errors too.
  await page.exposeFunction('__planifCspViolation', text => errors.push('CSP: ' + text));
  await page.addInitScript(() =>
    document.addEventListener('securitypolicyviolation', e =>
      globalThis.__planifCspViolation?.(`${e.violatedDirective} ${e.blockedURI || ''} ${e.sample || ''}`)
    )
  );
  // External fonts and Firebase are not needed by these scenarios.
  await context.route(/^https:\/\/(fonts\.|www\.gstatic\.com)/, route => route.abort());
  await page.goto(url);
  await ready(page);
  return {context, page, errors};
}

const ready = page =>
  page.waitForFunction(() =>
    Array.from(document.querySelectorAll('#appShell .screen:not([hidden])')).some(el => el.children.length)
  );

async function reload(page) {
  await page.reload();
  await ready(page);
}

