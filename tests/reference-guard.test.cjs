const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ui=fs.readFileSync('planif-ui.js','utf8');
const engine=fs.readFileSync('planif-engine.js','utf8');
const {hasCode}=require('./helpers/source.cjs');
new vm.Script(ui);
assert(hasCode(ui,'function refFinishEdit(saveChanges)'));
assert(hasCode(ui,'refPendingSet(true)'));
assert(hasCode(ui,'if(refDraft)return;'));
assert(hasCode(ui,'data-ref-cancel'));
assert(hasCode(ui,'data-ref-save'));
assert(hasCode(engine,'context.getCompletedIds?.()'));
const {createEngine}=require('../planif-engine.js');
const oldDate=new Date('2026-12-01T12:00:00');
const completed={planifId:'w0-q0',kind:'q',s:{old:true}};
const oldPlan={weeks:[{days:[{date:oldDate,items:[completed]}]}]};
const next={weeks:[{days:[{date:new Date(oldDate),items:[{planifId:'w0-q0',kind:'q',s:{new:true}}]}]}]};
const E=createEngine({getActivePlan:()=>({plan:oldPlan}),getCompletedIds:()=>['w0-q0']});
E.preservePastSessions(next);
assert.equal(next.weeks[0].days[0].items[0].s.old,true);
console.log('Reference editor and completed-session preservation guards OK');
